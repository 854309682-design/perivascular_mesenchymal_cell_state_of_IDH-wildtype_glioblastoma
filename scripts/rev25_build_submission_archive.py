#!/usr/bin/env python3
"""rev25 — rebuild the submission archive: `Paper_2_代码.zip` and the 备案 tarball.

The reviewers' C5 was that the code release did not contain the analyses behind Figures 3-5.
The revision ships them, so the archive has to be regenerated from the working tree rather
than hand-assembled. This script does that deterministically:

  1. `Paper_2_代码.zip` — the pipeline (`scripts/`), the environment record, the reportable
     result tables and the gene-set tables. Per-cell intermediate matrices (rev02_activity_*,
     rev05_reference_matrix, rev19_traj_axis_*) are excluded: they are regenerated by the
     scripts and are named as such in the manuscript's availability statement.
  2. `<...>_代码.zip` + the two 备案 forms + the merged `Paper_2_all.pdf` are packed into the
     tarball that the hospital submission expects.

Both outputs are written to `<name>.tmp` and moved into place with `os.replace`, so the script
can never read and write the same path (the failure mode that destroyed the manuscript once).

Run:
  GLIOMA_PROJ=/run/media/meng/Seqdata/glioma/Paper_2 \
  /home/meng/miniconda3/bin/python3 scripts/rev25_build_submission_archive.py
"""
import glob
import hashlib
import os
import re
import sys
import tarfile
import zipfile

PROJ = os.environ.get("GLIOMA_PROJ") or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEIAN = glob.glob(os.path.join(PROJ, "*备案*"))[0]
ZIP = os.path.join(BEIAN, "Paper_2_代码.zip")
TGZ = os.path.join(BEIAN, os.path.basename(BEIAN) + ".tar.gz")

EXCLUDE = re.compile(r"(rev02_activity_|rev05_reference_matrix|rev19_traj_axis_)")
EXCLUDE_EXT = (".pyc", ".png")


def md5p(p):
    h = hashlib.md5()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def collect():
    """(archive name, source path) pairs, in a stable order."""
    items = []
    for pat in ["scripts/*.py", "scripts/*.R", "scripts/*.sh"]:
        for p in sorted(glob.glob(os.path.join(PROJ, pat))):
            if p.endswith(EXCLUDE_EXT):
                continue
            items.append(("scripts/" + os.path.basename(p), p))
    for pat in ["env/versions.txt", "tables/*.tsv", "tables/*.csv"]:
        for p in sorted(glob.glob(os.path.join(PROJ, pat))):
            items.append((os.path.relpath(p, PROJ), p))
    for pat in ["results/revision/*", "results/multicohort/*",
                "results/scenic/rev01_subsample.tsv",
                "results/step04_traj/mes_transition_program_core.tsv"]:
        for p in sorted(glob.glob(os.path.join(PROJ, pat))):
            if not os.path.isfile(p) or p.endswith(EXCLUDE_EXT) or EXCLUDE.search(p):
                continue
            items.append((os.path.relpath(p, PROJ), p))
    return items


def build_zip():
    items = collect()
    tmp = ZIP + ".tmp"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
        seen = set()
        for arc, src in items:
            d = os.path.dirname(arc)
            if d and d not in seen:                     # keep the directory entries
                z.writestr(d + "/", "")
                seen.add(d)
            z.write(src, arc)
    os.replace(tmp, ZIP)
    with zipfile.ZipFile(ZIP) as z:
        bad = z.testzip()
    total = sum(os.path.getsize(s) for _, s in items)
    print(f"  {os.path.basename(ZIP)}: {len(items)} files, zip test "
          f"{'ok' if bad is None else 'BAD:' + str(bad)}, raw {total/1e6:.2f} MB, "
          f"md5 {md5p(ZIP)}")
    return items


def build_tar():
    members = [ZIP] + sorted(glob.glob(os.path.join(BEIAN, "文章1备案*"))) + \
              [os.path.join(BEIAN, "Paper_2_all.pdf")]
    missing = [m for m in members if not os.path.exists(m)]
    if missing:
        print(f"  NOT building the tarball: missing {missing}")
        return False
    tmp = TGZ + ".tmp"
    with tarfile.open(tmp, "w:gz") as t:
        for m in members:
            t.add(m, arcname=os.path.basename(m))
    os.replace(tmp, TGZ)
    with tarfile.open(TGZ) as t:
        names = t.getnames()
    print(f"  {os.path.basename(TGZ)}: {len(names)} entries {names}, md5 {md5p(TGZ)}")
    return True


def main():
    print("rebuilding the submission archive")
    items = build_zip()
    for f in ["Paper_2_all.pdf"]:
        p = os.path.join(BEIAN, f)
        print(f"  {f}: {'present md5 ' + md5p(p) if os.path.exists(p) else 'MISSING'}")
    build_tar()
    return 0


if __name__ == "__main__":
    sys.exit(main())
